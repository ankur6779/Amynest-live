#!/usr/bin/env node
/**
 * Emit sync build-time metadata from phonics-audio-map.json.
 * Used for availability gates without loading the 650KB+ JSON chunk.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const JSON_PATH = join(REPO_ROOT, "artifacts/kidschedule/src/data/phonics-audio-map.json");
const OUT_PATH = join(REPO_ROOT, "artifacts/kidschedule/src/data/phonics-audio-map-meta.ts");

const raw = JSON.parse(readFileSync(JSON_PATH, "utf8"));
const assetCount = Object.keys(raw.assets ?? {}).length;
const version = Number(raw.version ?? 0);
const libraryVersion = Number(raw.libraryVersion ?? 0);

const contents = `/** Auto-generated by scripts/gen-phonics-audio-map-meta.mjs — do not edit manually. */
export const PHONICS_BUNDLED_ASSET_COUNT = ${assetCount};
export const PHONICS_BUNDLED_VERSION = ${version};
export const PHONICS_BUNDLED_LIBRARY_VERSION = ${libraryVersion};
`;

writeFileSync(OUT_PATH, contents, "utf8");
console.log(`[gen-phonics-audio-map-meta] wrote ${assetCount} assets → ${OUT_PATH}`);
