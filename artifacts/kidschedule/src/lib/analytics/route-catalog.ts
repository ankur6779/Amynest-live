function specificity(pattern: string): number {
  const params = (pattern.match(/:[^/]+/g) ?? []).length;
  return pattern.length - params * 8;
}

export function matchAppRoute(path: string): string {
  const clean = (path.split("?")[0] || "/").replace(/\/+$/, "") || "/";
  let best = clean;
  let bestScore = -1;
  for (const pattern of APP_ROUTE_PATTERNS) {
    const source = pattern
      .replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
      .replace(/:[^/]+/g, "[^/]+");
    const re = new RegExp(`^${source}$`);
    if (!re.test(clean)) continue;
    const score = specificity(pattern);
    if (score > bestScore) {
      best = pattern;
      bestScore = score;
    }
  }
  return best;
}

export function featureForRoute(path: string): string | null {
  const pattern = matchAppRoute(path);
  if (pattern.startsWith("/birth-sky")) return "birth_sky";
  return FEATURE_BY_ROUTE[pattern as AppRoutePattern] ?? null;
}
